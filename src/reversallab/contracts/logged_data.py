"""The single-position contextual-bandit logged-data contract.

See ``docs/data_contract.md`` for the statistical meaning of every field.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import numpy.typing as npt

from reversallab.contracts.validation import (
    PROBABILITY_RANGE_ATOL,
    PROPENSITY_CONSISTENCY_ATOL,
    PROPENSITY_CONSISTENCY_RTOL,
    FloatArray,
    IntArray,
    as_readonly,
    to_action_array,
    to_float_array,
    validate_action_distribution,
)
from reversallab.exceptions import DataValidationError


@dataclass(frozen=True, eq=False)
class LoggedBanditData:
    """Validated, immutable batch of N logged single-position bandit interactions.

    Each observation ``i`` is a tuple ``(x_i, a_i, r_i, p_i)`` generated by the
    logging policy ``pi_0``: context ``x_i ~ P(x)``, action ``a_i ~ pi_0(.|x_i)``,
    reward ``r_i ~ P(r | x_i, a_i)``, and ``p_i = pi_0(a_i | x_i)``.

    Attributes:
        context: ``(N, D)`` context features observed *before* the action was chosen.
        action: ``(N,)`` integer index in ``[0, K)`` of the action that was logged.
        reward: ``(N,)`` observed scalar reward for the logged action only.
        logging_propensity: ``(N,)`` probability ``pi_0(a_i | x_i)`` that the logging
            policy assigned to the logged action. Must be strictly positive.
        n_actions: number of possible actions ``K``.
        logging_action_dist: optional ``(N, K)`` full logging distribution
            ``pi_0(. | x_i)``. When present, support of the evaluation policy can be
            verified for *every* action, not just the logged one.
        group_id: optional ``(N,)`` identifier of the dependence unit (user, session).
            Not used by M2 estimators, which assume i.i.d. observations; recorded so
            that later uncertainty methods can resample by group.
    """

    context: FloatArray
    action: IntArray
    reward: FloatArray
    logging_propensity: FloatArray
    n_actions: int
    logging_action_dist: FloatArray | None = None
    group_id: npt.NDArray[np.generic] | None = field(default=None)

    def __post_init__(self) -> None:
        if isinstance(self.n_actions, bool) or not isinstance(self.n_actions, int | np.integer):
            raise DataValidationError(f"`n_actions` must be an int, got {self.n_actions!r}.")
        n_actions = int(self.n_actions)
        if n_actions < 1:
            raise DataValidationError(f"`n_actions` must be >= 1, got {n_actions}.")

        context = to_float_array(self.context, name="context", ndim=2)
        n_samples = context.shape[0]
        if n_samples < 1:
            raise DataValidationError("Logged data must contain at least one observation.")

        action = to_action_array(self.action, n_actions=n_actions)
        reward = to_float_array(self.reward, name="reward", ndim=1)
        propensity = to_float_array(self.logging_propensity, name="logging_propensity", ndim=1)

        for name, arr in (
            ("action", action),
            ("reward", reward),
            ("logging_propensity", propensity),
        ):
            if arr.shape[0] != n_samples:
                raise DataValidationError(
                    f"`{name}` has {arr.shape[0]} rows but `context` has {n_samples}; "
                    "all per-observation arrays must have the same length N."
                )

        if np.any(propensity <= 0.0):
            n_bad = int(np.count_nonzero(propensity <= 0.0))
            raise DataValidationError(
                f"`logging_propensity` has {n_bad} non-positive value(s). A logged action must "
                "have positive probability under the logging policy; zero propensities indicate "
                "corrupt data or a deterministic logger. They are not replaced with epsilon."
            )
        if np.any(propensity > 1.0 + PROBABILITY_RANGE_ATOL):
            raise DataValidationError("`logging_propensity` contains values greater than 1.")

        logging_dist: FloatArray | None = None
        if self.logging_action_dist is not None:
            logging_dist = validate_action_distribution(
                self.logging_action_dist,
                n_samples=n_samples,
                n_actions=n_actions,
                name="logging_action_dist",
            )
            implied = logging_dist[np.arange(n_samples), action]
            if not np.allclose(
                implied,
                propensity,
                rtol=PROPENSITY_CONSISTENCY_RTOL,
                atol=PROPENSITY_CONSISTENCY_ATOL,
            ):
                worst = int(np.argmax(np.abs(implied - propensity)))
                raise DataValidationError(
                    "`logging_propensity` disagrees with `logging_action_dist` at the logged "
                    f"action (row {worst}: {propensity[worst]!r} vs {implied[worst]!r})."
                )
            as_readonly(logging_dist)

        group_id = None
        if self.group_id is not None:
            group_id = np.array(self.group_id, copy=True)
            if group_id.shape != (n_samples,):
                raise DataValidationError(
                    f"`group_id` must have shape ({n_samples},), got {group_id.shape}."
                )
            as_readonly(group_id)

        object.__setattr__(self, "n_actions", n_actions)
        object.__setattr__(self, "context", as_readonly(context))
        object.__setattr__(self, "action", as_readonly(action))
        object.__setattr__(self, "reward", as_readonly(reward))
        object.__setattr__(self, "logging_propensity", as_readonly(propensity))
        object.__setattr__(self, "logging_action_dist", logging_dist)
        object.__setattr__(self, "group_id", group_id)

    @property
    def n_samples(self) -> int:
        return int(self.context.shape[0])

    @property
    def context_dim(self) -> int:
        return int(self.context.shape[1])
